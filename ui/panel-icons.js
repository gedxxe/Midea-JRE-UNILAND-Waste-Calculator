const NS = 'http://www.w3.org/2000/svg';
export function panelIcon(name) {
  const nodes = geometry[name];
  if (!nodes) throw new RangeError('Unknown panel icon');
  const svg = document.createElementNS(NS, 'svg');
  for (const [key, value] of Object.entries({
    viewBox: '0 0 24 24',
    width: '20',
    height: '20',
    fill: 'none',
    stroke: 'currentColor',
    'stroke-width': '1.8',
    'stroke-linecap': 'round',
    'stroke-linejoin': 'round',
    'aria-hidden': 'true',
    focusable: 'false',
    class: 'panel-svg',
  }))
    svg.setAttribute(key, value);
  for (const [tag, attributes] of nodes) {
    const node = document.createElementNS(NS, tag);
    for (const [key, value] of Object.entries(attributes)) node.setAttribute(key, value);
    svg.append(node);
  }
  return svg;
}
export function setPanelIcon(element, name) {
  if (element.dataset.currentIcon === name) return;
  element.replaceChildren(panelIcon(name));
  element.dataset.currentIcon = name;
}
export function mountPanelIcons(root = document) {
  for (const element of root.querySelectorAll('[data-panel-icon]'))
    setPanelIcon(element, element.dataset.panelIcon);
}
// Original formula marks. They supplement the full gas names rather than replace their labels.
